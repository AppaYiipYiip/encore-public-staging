import 'dart:convert';

import 'package:drift/drift.dart';

import '../../core/clock.dart';
import '../db/app_database.dart';
import 'fingerprint.dart';
import 'outbox.dart';

/// What a screen may ask of playlist editing, whichever kind of server it is talking to.
abstract interface class PlaylistEditor {
  /// Creates a playlist named [name] holding [trackIds]; returns its id. An empty name becomes "New playlist".
  Future<String> create(String name, {List<String> trackIds = const []});

  /// Appends songs. `false` (nothing changed) when the playlist cannot be edited: unknown, deleted, or made by the server.
  Future<bool> addTracks(String playlistId, List<String> trackIds);

  /// Removes the entry at [position] (0-based, as shown on the page).
  Future<bool> removeAt(String playlistId, int position);

  Future<bool> rename(String playlistId, String name);

  Future<void> delete(String playlistId);
}

/// Local-first playlist editing (create, add, remove, rename, delete).
///
/// Every operation changes the local database first - the UI reacts through
/// its streams, offline included - and queues the server write in the outbox,
/// which delivers in order (see [OutboxProcessor]).
///
/// A playlist created offline gets a *local id* ([localPrefix]); the id the
/// server assigns replaces it as soon as the create is delivered
/// ([adoptServerId]), carrying over entries, pins and queued edits.
class PlaylistMutations implements PlaylistEditor {
  PlaylistMutations({
    required AppDatabase db,
    required this.serverId,
    Clock clock = const SystemClock(),
    this.ownerName,
    void Function()? onQueued,
  })  : _db = db,
        _clock = clock,
        _onQueued = onQueued;

  /// Prefix of playlist ids that exist only on this phone so far.
  static const String localPrefix = 'local-';

  static bool isLocalId(String id) => id.startsWith(localPrefix);

  final AppDatabase _db;
  final Clock _clock;
  final int serverId;

  /// Shown as the owner of playlists created here.
  final String? ownerName;
  final void Function()? _onQueued;

  int _counter = 0;

  // ------------------------------------------------------------------ create

  /// Creates a playlist named [name] holding [trackIds]; returns its (local)
  /// id. An empty name becomes "New playlist".
  @override
  Future<String> create(String name, {List<String> trackIds = const []}) async {
    final nowMs = _clock.now().millisecondsSinceEpoch;
    final id = '$localPrefix${nowMs.toRadixString(36)}-${_counter++}';
    final title = name.trim().isEmpty ? 'New playlist' : name.trim();

    await _db.transaction(() async {
      final durationSec = await _durationOf(trackIds);
      await _db.into(_db.playlists).insert(PlaylistsCompanion.insert(
            serverId: serverId,
            id: id,
            name: title,
            owner: Value(ownerName),
            songCount: Value(trackIds.length),
            durationSec: Value(durationSec),
            createdAtMs: Value(nowMs),
            changedAtMs: Value(nowMs),
            memberSetHash: Value(memberSetHashOf(trackIds)),
            entriesFetchedAtMs: Value(nowMs),
          ));
      if (trackIds.isNotEmpty) {
        await _db.batch((b) {
          b.insertAll(_db.playlistEntries, [
            for (var i = 0; i < trackIds.length; i++)
              PlaylistEntriesCompanion.insert(
                serverId: serverId,
                playlistId: id,
                position: i,
                trackId: trackIds[i],
              ),
          ]);
        });
      }
      await _enqueue(OutboxKind.playlistCreate, {
        'name': title,
        'songIds': trackIds,
        'localId': id,
      });
    });
    _onQueued?.call();
    return id;
  }

  // --------------------------------------------------------------------- add

  /// Appends [trackIds] to [playlistId]. Returns `false` (and changes
  /// nothing) when the playlist cannot be edited: unknown, deleted, or
  /// generated by the server.
  @override
  Future<bool> addTracks(String playlistId, List<String> trackIds) async {
    if (trackIds.isEmpty) return true;
    final row = await _editable(playlistId);
    if (row == null) return false;

    await _db.transaction(() async {
      final maxPos = await _maxPosition(playlistId);
      final durationSec = await _durationOf(trackIds);
      await _db.batch((b) {
        b.insertAll(_db.playlistEntries, [
          for (var i = 0; i < trackIds.length; i++)
            PlaylistEntriesCompanion.insert(
              serverId: serverId,
              playlistId: playlistId,
              position: maxPos + 1 + i,
              trackId: trackIds[i],
            ),
        ]);
      });
      await _touch(playlistId,
          countDelta: trackIds.length, durationDelta: durationSec);
      await _enqueueUpdate(playlistId, add: trackIds);
    });
    _onQueued?.call();
    return true;
  }

  // ------------------------------------------------------------------ remove

  /// Removes the entry at [position] (0-based, as shown on the page).
  @override
  Future<bool> removeAt(String playlistId, int position) async {
    final row = await _editable(playlistId);
    if (row == null) return false;

    final removed = await _db.transaction<bool>(() async {
      final entry = await (_db.select(_db.playlistEntries)
            ..where((e) =>
                e.serverId.equals(serverId) &
                e.playlistId.equals(playlistId) &
                e.position.equals(position)))
          .getSingleOrNull();
      if (entry == null) return false;

      final durationSec = await _durationOf([entry.trackId]);
      await (_db.delete(_db.playlistEntries)
            ..where((e) =>
                e.serverId.equals(serverId) &
                e.playlistId.equals(playlistId) &
                e.position.equals(position)))
          .go();
      // Close the gap in two steps so no intermediate state collides on the
      // (playlist, position) key.
      await _db.customUpdate(
        'UPDATE playlist_entries SET position = -position '
        'WHERE server_id = ?1 AND playlist_id = ?2 AND position > ?3',
        variables: [
          Variable<int>(serverId),
          Variable<String>(playlistId),
          Variable<int>(position),
        ],
        updates: {_db.playlistEntries},
        updateKind: UpdateKind.update,
      );
      await _db.customUpdate(
        'UPDATE playlist_entries SET position = -position - 1 '
        'WHERE server_id = ?1 AND playlist_id = ?2 AND position < 0',
        variables: [Variable<int>(serverId), Variable<String>(playlistId)],
        updates: {_db.playlistEntries},
        updateKind: UpdateKind.update,
      );
      await _touch(playlistId, countDelta: -1, durationDelta: -durationSec);
      await _enqueueUpdate(
        playlistId,
        removeIdx: [position],
        removeIds: [entry.trackId],
      );
      return true;
    });
    if (removed) _onQueued?.call();
    return removed;
  }

  // ------------------------------------------------------------------ rename

  @override
  Future<bool> rename(String playlistId, String name) async {
    final title = name.trim();
    if (title.isEmpty) return false;
    final row = await _editable(playlistId);
    if (row == null) return false;

    await _db.transaction(() async {
      await (_db.update(_db.playlists)
            ..where(
                (p) => p.serverId.equals(serverId) & p.id.equals(playlistId)))
          .write(PlaylistsCompanion(name: Value(title)));
      await _enqueueUpdate(playlistId, name: title);
    });
    _onQueued?.call();
    return true;
  }

  // ------------------------------------------------------------------ delete

  @override
  Future<void> delete(String playlistId) async {
    await _db.transaction(() async {
      final pending = await _pendingOpsFor(playlistId);
      final neverDelivered = isLocalId(playlistId) &&
          pending.any((o) => o.kind == OutboxKind.playlistCreate);

      // Whatever was queued for this playlist no longer matters.
      for (final op in pending) {
        await (_db.delete(_db.outbox)..where((o) => o.id.equals(op.id))).go();
      }
      await (_db.delete(_db.pins)
            ..where((p) =>
                p.serverId.equals(serverId) &
                p.targetType.equals('playlist') &
                p.targetId.equals(playlistId)))
          .go();

      if (neverDelivered) {
        // The server never heard of it: forget it completely.
        await (_db.delete(_db.playlistEntries)
              ..where((e) =>
                  e.serverId.equals(serverId) &
                  e.playlistId.equals(playlistId)))
            .go();
        await (_db.delete(_db.playlists)
              ..where(
                  (p) => p.serverId.equals(serverId) & p.id.equals(playlistId)))
            .go();
        return;
      }

      await (_db.update(_db.playlists)
            ..where(
                (p) => p.serverId.equals(serverId) & p.id.equals(playlistId)))
          .write(PlaylistsCompanion(
              deletedAtMs: Value(_clock.now().millisecondsSinceEpoch)));
      await _enqueue(OutboxKind.playlistDelete, {'id': playlistId});
    });
    _onQueued?.call();
  }

  // ----------------------------------------------------------- id adoption

  /// Replaces the local id [localId] by the server's [serverPlaylistId] in the
  /// playlist row, its entries, pins and every queued edit. Called by the
  /// outbox right after a create was delivered.
  /// The server id a local playlist became, or `null` while it has none.
  static Future<String?> aliasFor(
    AppDatabase db,
    int serverId,
    String localId,
  ) async {
    final row = await (db.select(db.playlistAliases)
          ..where(
              (a) => a.serverId.equals(serverId) & a.localId.equals(localId)))
        .getSingleOrNull();
    return row?.serverPlaylistId;
  }

  /// Server playlist ids that already belong to one of this phone's playlists.
  static Future<Set<String>> adoptedServerIds(
    AppDatabase db,
    int serverId,
  ) async {
    final rows = await (db.select(db.playlistAliases)
          ..where((a) => a.serverId.equals(serverId)))
        .get();
    return {for (final r in rows) r.serverPlaylistId};
  }

  static Future<void> adoptServerId(
    AppDatabase db,
    int serverId, {
    required String localId,
    required String serverPlaylistId,
  }) async {
    if (localId == serverPlaylistId) return;
    await db.transaction(() async {
      // A sync may have fetched the new playlist already: the local row (with
      // its pins and queued edits) wins, so drop the fetched copy.
      await (db.delete(db.playlistEntries)
            ..where((e) =>
                e.serverId.equals(serverId) &
                e.playlistId.equals(serverPlaylistId)))
          .go();
      await (db.delete(db.playlists)
            ..where((p) =>
                p.serverId.equals(serverId) & p.id.equals(serverPlaylistId)))
          .go();

      Future<void> rename(String table, String column) => db.customUpdate(
            'UPDATE $table SET $column = ?1 '
            'WHERE server_id = ?2 AND $column = ?3',
            variables: [
              Variable<String>(serverPlaylistId),
              Variable<int>(serverId),
              Variable<String>(localId),
            ],
            updates: {
              if (table == 'playlists') db.playlists,
              if (table == 'playlist_entries') db.playlistEntries,
            },
            updateKind: UpdateKind.update,
          );
      await rename('playlists', 'id');
      await rename('playlist_entries', 'playlist_id');
      await db.into(db.playlistAliases).insertOnConflictUpdate(
            PlaylistAliasesCompanion.insert(
              serverId: serverId,
              localId: localId,
              serverPlaylistId: serverPlaylistId,
            ),
          );
      await db.customUpdate(
        "UPDATE pins SET target_id = ?1 WHERE server_id = ?2 "
        "AND target_type = 'playlist' AND target_id = ?3",
        variables: [
          Variable<String>(serverPlaylistId),
          Variable<int>(serverId),
          Variable<String>(localId),
        ],
        updates: {db.pins},
        updateKind: UpdateKind.update,
      );

      // Queued edits that still carry the local id.
      final rows = await (db.select(db.outbox)
            ..where((o) =>
                o.serverId.equals(serverId) & o.status.equals('pending')))
          .get();
      for (final row in rows) {
        final payload = _decode(row.payloadJson);
        var changed = false;
        for (final key in const ['playlistId', 'id']) {
          if (payload[key] == localId &&
              (row.kind == OutboxKind.playlistUpdate ||
                  row.kind == OutboxKind.playlistDelete)) {
            payload[key] = serverPlaylistId;
            changed = true;
          }
        }
        if (changed) {
          await (db.update(db.outbox)..where((o) => o.id.equals(row.id)))
              .write(OutboxCompanion(payloadJson: Value(jsonEncode(payload))));
        }
      }
    });
  }

  /// Drops a phone-only playlist whose server id could not be determined.
  /// Queued edits for it are dropped too; the server's copy arrives with the
  /// next sync.
  static Future<void> discardLocal(
      AppDatabase db, int serverId, String localId) async {
    await db.transaction(() async {
      await (db.delete(db.playlistEntries)
            ..where((e) =>
                e.serverId.equals(serverId) & e.playlistId.equals(localId)))
          .go();
      await (db.delete(db.playlists)
            ..where((p) => p.serverId.equals(serverId) & p.id.equals(localId)))
          .go();
      await (db.delete(db.pins)
            ..where((p) =>
                p.serverId.equals(serverId) &
                p.targetType.equals('playlist') &
                p.targetId.equals(localId)))
          .go();
      final rows = await (db.select(db.outbox)
            ..where((o) =>
                o.serverId.equals(serverId) & o.status.equals('pending')))
          .get();
      for (final row in rows) {
        if (_mentions(row, localId)) {
          await (db.delete(db.outbox)..where((o) => o.id.equals(row.id))).go();
        }
      }
    });
  }

  /// Ids of playlists with edits that were not delivered yet. The sync keeps
  /// their local state instead of overwriting it with the server's older one.
  static Future<Set<String>> pendingPlaylistIds(
      AppDatabase db, int serverId) async {
    final rows = await (db.select(db.outbox)
          ..where(
              (o) => o.serverId.equals(serverId) & o.status.equals('pending')))
        .get();
    final ids = <String>{};
    for (final row in rows) {
      switch (row.kind) {
        case OutboxKind.playlistUpdate:
          final id = _decode(row.payloadJson)['playlistId'];
          if (id is String) ids.add(id);
        case OutboxKind.playlistDelete:
          final id = _decode(row.payloadJson)['id'];
          if (id is String) ids.add(id);
        case OutboxKind.playlistCreate:
          final id = _decode(row.payloadJson)['localId'];
          if (id is String) ids.add(id);
      }
    }
    return ids;
  }

  // ----------------------------------------------------------------- helpers

  static Map<String, dynamic> _decode(String json) {
    try {
      return (jsonDecode(json) as Map).cast<String, dynamic>();
    } on Object {
      return <String, dynamic>{};
    }
  }

  Future<PlaylistRow?> _editable(String playlistId) async {
    final row = await (_db.select(_db.playlists)
          ..where((p) => p.serverId.equals(serverId) & p.id.equals(playlistId)))
        .getSingleOrNull();
    if (row == null || row.deletedAtMs != null || row.readonly) return null;
    return row;
  }

  Future<int> _maxPosition(String playlistId) async {
    final maxCol = _db.playlistEntries.position.max();
    final q = _db.selectOnly(_db.playlistEntries)
      ..addColumns([maxCol])
      ..where(_db.playlistEntries.serverId.equals(serverId) &
          _db.playlistEntries.playlistId.equals(playlistId));
    return (await q.getSingle()).read(maxCol) ?? -1;
  }

  Future<int> _durationOf(List<String> trackIds) async {
    if (trackIds.isEmpty) return 0;
    final rows = await (_db.select(_db.tracks)
          ..where(
              (t) => t.serverId.equals(serverId) & t.id.isIn(trackIds.toSet())))
        .get();
    final byId = {for (final t in rows) t.id: t.durationSec ?? 0};
    return trackIds.fold<int>(0, (sum, id) => sum + (byId[id] ?? 0));
  }

  /// Keeps the list header (count, length, content hash) in step with the
  /// entries without waiting for the server.
  Future<void> _touch(
    String playlistId, {
    required int countDelta,
    required int durationDelta,
  }) async {
    final ids = await (_db.select(_db.playlistEntries)
          ..where((e) =>
              e.serverId.equals(serverId) & e.playlistId.equals(playlistId))
          ..orderBy([(e) => OrderingTerm.asc(e.position)]))
        .map((e) => e.trackId)
        .get();
    final row = await (_db.select(_db.playlists)
          ..where((p) => p.serverId.equals(serverId) & p.id.equals(playlistId)))
        .getSingle();
    await (_db.update(_db.playlists)
          ..where((p) => p.serverId.equals(serverId) & p.id.equals(playlistId)))
        .write(PlaylistsCompanion(
      songCount: Value(ids.length),
      durationSec: Value((row.durationSec + durationDelta).clamp(0, 1 << 30)),
      memberSetHash: Value(memberSetHashOf(ids)),
      entriesFetchedAtMs: Value(_clock.now().millisecondsSinceEpoch),
    ));
  }

  Future<List<OutboxRow>> _pendingOpsFor(String playlistId) async {
    final rows = await (_db.select(_db.outbox)
          ..where(
              (o) => o.serverId.equals(serverId) & o.status.equals('pending')))
        .get();
    return [
      for (final row in rows)
        if (_mentions(row, playlistId)) row,
    ];
  }

  static bool _mentions(OutboxRow row, String playlistId) {
    final p = _decode(row.payloadJson);
    return switch (row.kind) {
      OutboxKind.playlistCreate => p['localId'] == playlistId,
      OutboxKind.playlistUpdate => p['playlistId'] == playlistId,
      OutboxKind.playlistDelete => p['id'] == playlistId,
      _ => false,
    };
  }

  Future<void> _enqueue(String kind, Map<String, Object?> payload) =>
      _db.into(_db.outbox).insert(OutboxCompanion.insert(
            serverId: serverId,
            kind: kind,
            payloadJson: jsonEncode(payload),
            createdAtMs: _clock.now().millisecondsSinceEpoch,
          ));

  /// Queues an edit. Consecutive additions to one playlist are merged into a
  /// single request by the outbox when it delivers them.
  Future<void> _enqueueUpdate(
    String playlistId, {
    List<String> add = const [],
    List<int> removeIdx = const [],
    List<String> removeIds = const [],
    String? name,
  }) async {
    await _enqueue(OutboxKind.playlistUpdate, {
      'playlistId': playlistId,
      if (add.isNotEmpty) 'add': add,
      if (removeIdx.isNotEmpty) 'removeIdx': removeIdx,
      if (removeIds.isNotEmpty) 'removeIds': removeIds,
      if (name != null) 'name': name,
    });
  }
}
