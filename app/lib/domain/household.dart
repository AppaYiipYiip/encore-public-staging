/// What is "mine" on a server that a whole household shares (ADR-049).
///
/// Every account on the server has its own likes, play counts, history and
/// playlists, but the catalogue itself is common. A phone must open on *this*
/// person's music; everyone else's stays one tap away, not in the face.
library;

/// Which part of the server "Your Library" lists.
///
/// Your Library is the person's own, always (owner, 2026-10-22: "only my music should be the default"). The rest of the server is a view
/// they ask for, and a new account's empty library says how to fill it instead of showing everybody else's.
enum LibraryScope {
  /// What this account has played, liked, rated, downloaded or put into one of
  /// its own playlists. The default.
  mine,

  /// Every album and artist the server has.
  everything;

  /// An old install may have saved `automatic` (the app chose for the person: the whole server until a few albums were played): that is
  /// "mine" now, as is anything unknown.
  static LibraryScope byName(String? name) => values.firstWhere(
        (s) => s.name == name,
        orElse: () => LibraryScope.mine,
      );
}

/// How a playlist relates to the account that is signed in.
enum PlaylistOwnership {
  /// Created by this account; it can be edited.
  mine,

  /// Generated by the server for this account (a smart playlist); read-only.
  madeForMe,

  /// Somebody else's public playlist.
  shared,
}

/// Two account names refer to the same person (the server compares them
/// without regard to case).
bool sameAccount(String? a, String? b) =>
    (a ?? '').trim().toLowerCase() == (b ?? '').trim().toLowerCase();

/// Classifies a playlist for [me], the signed-in user name.
///
/// Servers that do not report an owner are single-user in practice, so an
/// unknown owner counts as mine.
PlaylistOwnership playlistOwnership({
  required String? owner,
  required bool readonly,
  required String? me,
}) {
  final isMine = owner == null || me == null || sameAccount(owner, me);
  if (!isMine) return PlaylistOwnership.shared;
  return readonly ? PlaylistOwnership.madeForMe : PlaylistOwnership.mine;
}

/// The albums and artists this account has a relationship with.
class MyMusic {
  const MyMusic({this.albumIds = const {}, this.artistIds = const {}});

  static const empty = MyMusic();

  final Set<String> albumIds;
  final Set<String> artistIds;

  bool get isEmpty => albumIds.isEmpty && artistIds.isEmpty;

  bool hasAlbum(String id) => albumIds.contains(id);
  bool hasArtist(String? id) => id != null && artistIds.contains(id);

  @override
  bool operator ==(Object other) =>
      other is MyMusic &&
      other.albumIds.length == albumIds.length &&
      other.artistIds.length == artistIds.length &&
      other.albumIds.containsAll(albumIds) &&
      other.artistIds.containsAll(artistIds);

  @override
  int get hashCode => Object.hash(albumIds.length, artistIds.length);
}
