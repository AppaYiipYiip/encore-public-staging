def run(*args: str, cwd: Path | None = None, stdin: str | None = None, check: bool = False) -> subprocess.CompletedProcess[str]:
    return subprocess.run(args, cwd=cwd, input=stdin, capture_output=True, text=True, encoding="utf-8", errors="replace", check=check)


def compose(stack: Path, *args: str, stdin: str | None = None) -> subprocess.CompletedProcess[str]:
    return run("docker", "compose", *args, cwd=stack, stdin=stdin)


def env_of(stack: Path) -> dict[str, str]:
    return dict(line.split("=", 1) for line in (stack / ".env").read_text(encoding="utf-8").splitlines() if "=" in line)


def set_env(stack: Path, key: str, value: str) -> None:
    lines = [line for line in (stack / ".env").read_text(encoding="utf-8").splitlines() if not line.startswith(key + "=")]
    (stack / ".env").write_text("\n".join([*lines, f"{key}={value}"]) + "\n", encoding="utf-8")


# ------------------------------------------------------------------------------------------------------------ up / down


def up(stack: Path, rebuild: bool) -> None:
    if rebuild or run("docker", "image", "inspect", IMAGE).returncode != 0:
        print("building the image from this checkout (a few minutes the first time) ...")
        run("docker", "build", "-t", IMAGE, str(REPO / "server" / "encore_server"), check=True)
    stack.mkdir(parents=True, exist_ok=True)
    music = stack / "music"
    music.mkdir(exist_ok=True)
    shutil.copy(REPO / "server" / "encore_server" / "deploy" / "compose.yaml", stack / "compose.yaml")
    if not (stack / ".env").exists():
        values = {
            "ENCORE_MUSIC_DIR": str(music).replace("\\", "/"),
            "ENCORE_PORT": PORT,
            "ENCORE_IMAGE": IMAGE.split(":")[0],
            "ENCORE_TAG": IMAGE.split(":")[1],
            "ENCORE_SERVER_NAME": "Audit test server",
            "ENCORE_NAVIDROME_ADMIN_USER": "encore-admin",
            "ENCORE_NAVIDROME_ADMIN_PASSWORD": secrets.token_urlsafe(18),
            "ENCORE_YOUTUBE": "0",
            "ENCORE_AUTO_TOOLS": "0",
            "TEST_OWNER_PASSWORD": secrets.token_urlsafe(14),
        }
        (stack / ".env").write_text("\n".join(f"{k}={v}" for k, v in values.items()) + "\n", encoding="utf-8")
    for folder, stem, title, artist, album, track, seconds in TRACKS:
        (music / folder).mkdir(exist_ok=True)
        if (music / folder / f"{stem}.flac").exists():
            continue
        done = run(
            "docker", "run", "--rm", "-v", f"{music}:/music", "--entrypoint", "ffmpeg", IMAGE, "-y", "-loglevel", "error",
            "-f", "lavfi", "-i", f"sine=frequency={220 + track * 55}:duration={seconds}",
            "-metadata", f"title={title}", "-metadata", f"artist={artist}", "-metadata", f"album={album}",
            "-metadata", f"track={track}", "-metadata", f"album_artist={artist}", "-c:a", "flac", f"/music/{folder}/{stem}.flac",
        )
        print("track", "ok" if done.returncode == 0 else "FAILED", folder, stem, done.stderr.strip()[:100])
    compose(stack, "up", "-d")
    for _ in range(40):
        if "healthy" in compose(stack, "ps", "encore-server", "--format", "{{.Status}}").stdout:
            break
        time.sleep(3)
    payload = json.dumps({"username": OWNER, "password": env_of(stack)["TEST_OWNER_PASSWORD"], "name": "Audit Owner"})
    done = compose(stack, "exec", "-T", "encore-server", "python", "-m", "encore_server", "setup", stdin=payload)
    print("first-install step:", done.stdout.strip().replace("\n", ", ") or done.stderr.strip()[:200])
    print(f"ready: http://127.0.0.1:{PORT}  (an emulator reaches it at 10.0.2.2:{PORT}; user {OWNER}, the password is in {stack / '.env'}, key TEST_OWNER_PASSWORD)")


# ------------------------------------------------------------------------------------------------------------ http


class Phone:
    """What a phone does: sign in once, then call with the device token."""

    def __init__(self, stack: Path) -> None:
        self.base = f"http://127.0.0.1:{PORT}"
        self.env = env_of(stack)
        self.token: str | None = None

    def call(self, method: str, path: str, body: object | None = None, raw: bool = False):
        request = urllib.request.Request(self.base + path, data=json.dumps(body).encode() if body is not None else None, method=method)
        request.add_header("Content-Type", "application/json")
        if self.token:
            request.add_header("Authorization", f"Bearer {self.token}")
        try:
            with urllib.request.urlopen(request, timeout=60) as response:
                text = response.read().decode("utf-8", "replace")
                return response.status, (text if raw else json.loads(text or "{}"))
        except urllib.error.HTTPError as error:
            text = error.read().decode("utf-8", "replace")
            try:
                return error.code, (text if raw else json.loads(text or "{}"))
            except ValueError:
                return error.code, text

    def sign_in(self) -> None:
        status, body = self.call("POST", "/encore/api/v1/auth/login", {"username": OWNER, "password": self.env["TEST_OWNER_PASSWORD"], "deviceName": "audit"})
        if status != 200:
            raise SystemExit(f"sign-in failed: {status} {body}")
        self.token = body["deviceToken"]

    def refs(self) -> dict[str, dict]:
        found: dict[str, dict] = {}
        since = "0"
        while True:
            status, body = self.call("GET", f"/encore/api/v1/library/files?since={since}&limit=500")
            assert status == 200, (status, body)
            found.update({r["id"]: r for r in body["refs"]})
            since = body["cursor"]
            if not body.get("more"):
                return found


def db_count(stack: Path, sql: str) -> str:
    code = f"import sqlite3;print(sqlite3.connect('/data/encore.db').execute({sql!r}).fetchone())"
    return compose(stack, "exec", "-T", "encore-server", "python", "-c", code).stdout.strip()


# ------------------------------------------------------------------------------------------------------------ the checks


def check_library(stack: Path) -> None:
    phone = Phone(stack)
    phone.sign_in()
    refs: dict[str, dict] = {}
    for _ in range(40):  # the library link runs 20 s after the start, after the music server has scanned
        refs = phone.refs()
        if refs:
            break
        time.sleep(5)
    print(f"{len(TRACKS)} files in the music folder; the server made {len(refs)} songs")
    for r in sorted(refs.values(), key=lambda x: x["title"]):
        print("  ", r["title"], "|", r["artists"], "|", r["durationMs"], "ms")
    print("song_file rows, distinct songs:", db_count(stack, "select count(*), count(distinct ref) from song_file"))
    print(f"wanted: {len(TRACKS)} songs ->", "PASS" if len(refs) == len(TRACKS) else "FAIL")


def check_outage(stack: Path) -> None:
    compose(stack, "stop", "navidrome")
    try:
        status, body = Phone(stack).call("POST", "/encore/api/v1/auth/login", {"username": OWNER, "password": env_of(stack)["TEST_OWNER_PASSWORD"], "deviceName": "audit"})
    finally:
        compose(stack, "start", "navidrome")
    print("sign-in with the CORRECT password while the music server is down:", status, json.dumps(body, ensure_ascii=False)[:160])
    print("wanted: 503 'not answering', not counted as a wrong guess ->", "PASS" if status == 503 else "FAIL")


def check_badsig(stack: Path) -> None:
    status, body = Phone(stack).call("GET", "/encore/stream/sr_00000000000000000000000000?p=pn_x&e=9999999999&sig=%C3%A9", raw=True)
    print("a song address with a non-ASCII signature, no login:", status, str(body)[:100])
    print("wanted: 401 ->", "PASS" if status == 401 else "FAIL")


def check_prune(stack: Path) -> None:
    music = Path(env_of(stack)["ENCORE_MUSIC_DIR"])
    away = stack / "music_away"
    away.mkdir(exist_ok=True)
    before = db_count(stack, "select count(*) from song_file")
    for child in list(music.iterdir()):
        shutil.move(str(child), str(away / child.name))
    try:
        scan = (
            "from encore_server.config import Settings;from encore_server.navidrome import NavidromeClient;import time;"
            "s=Settings.from_env();c=NavidromeClient(s.navidrome_url,s.navidrome_admin_user,s.navidrome_admin_password);"
            "c.start_scan(full=True);time.sleep(8);print('the music server now lists', len(c.songs(0,500) or []), 'songs')"
        )
        print(compose(stack, "exec", "-T", "encore-server", "python", "-c", scan).stdout.strip())
        seen = compose(stack, "logs", "encore-server").stdout.count("library linked")
        compose(stack, "restart", "encore-server")
        for _ in range(40):
            if compose(stack, "logs", "encore-server").stdout.count("library linked") > seen:
                break
            time.sleep(3)
        after = db_count(stack, "select count(*) from song_file")
    finally:
        for child in list(away.iterdir()):
            shutil.move(str(child), str(music / child.name))
    print("file links before:", before, "| after the empty answer:", after, "(the music is back in its folder now)")
    print("wanted: unchanged ->", "PASS" if before == after else "FAIL")


def check_transient(stack: Path) -> None:
    override = stack / "docker-compose.override.yml"
    override.write_text("services:\n  encore-server:\n    extra_hosts:\n" + "".join(f'      - "{h}:127.0.0.1"\n' for h in YOUTUBE_HOSTS), encoding="utf-8")
    set_env(stack, "ENCORE_YOUTUBE", "1")
    compose(stack, "up", "-d")
    for _ in range(40):
        if "healthy" in compose(stack, "ps", "encore-server", "--format", "{{.Status}}").stdout:
            break
        time.sleep(3)
    phone = Phone(stack)
    phone.sign_in()
    status, body = phone.call("POST", "/encore/api/v1/refs/resolve", {"songs": [{"title": "Maria Tambien", "artists": ["Khruangbin"], "durationMs": 215000}]})
    ref = body["items"][0]["id"]
    phone.call("PUT", f"/encore/api/v1/likes/{ref}", {})
    state: dict = {}
    for _ in range(40):
        status, state = phone.call("GET", f"/encore/api/v1/refs/{ref}/keep")
        if state.get("state") in ("failed", "kept", "none"):
            break
        time.sleep(3)
    status, answer = phone.call("POST", "/encore/api/v1/keep/progress", {"groups": [{"kind": "liked", "id": "liked"}]})
    group = answer["groups"][0]
    status, retry = phone.call("POST", "/encore/api/v1/keep/retry", {"kind": "liked", "id": "liked"})
    set_env(stack, "ENCORE_YOUTUBE", "0")
    override.unlink()
    compose(stack, "up", "-d")
    print("YouTube unreachable (its names point to the container itself; no traffic leaves the PC). The liked song is:", state)
    print("the download screen is told: failed", group["failed"], "retryable", group["retryable"], "| Retry asked for", retry.get("retried"), "songs")
    print("wanted: still waiting, or failed with Retry offered ->", "PASS" if group["retryable"] else "FAIL")


def connections(stack: Path) -> None:
    code = (
        "n=0\nfor f in ('/proc/net/tcp','/proc/net/tcp6'):\n    for line in open(f).read().splitlines()[1:]:\n"
        "        p=line.split()\n        if p[1].endswith(':11B5') and p[3]=='01': n+=1\nprint(n)\n"
    )
    print("established connections to the server's port 4533:", compose(stack, "exec", "-T", "encore-server", "python", "-c", code).stdout.strip())


