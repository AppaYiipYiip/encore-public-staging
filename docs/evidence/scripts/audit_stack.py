def check_revoke(stack: Path) -> None:
    """B-55: the person revokes one of their phones from another phone. A call that carries the revoked device's token is refused (that part is
    built); the app of build 125 does not carry a token, it carries the music-server login (u, t, s) and only NAMES its device in a header."""
    env = env_of(stack)
    name, password = OWNER, env["TEST_OWNER_PASSWORD"]
    phone_a, phone_b = Phone(stack), Phone(stack)
    answers = []
    for phone, label in ((phone_a, "audit-lost-phone"), (phone_b, "audit-other-phone")):
        status, body = phone.call("POST", "/encore/api/v1/auth/login", {"username": name, "password": password, "deviceName": label})
        assert status == 200, (status, body)
        phone.token, phone.device = body["deviceToken"], body["device"]["id"]
        answers.append(phone.device)
    status, body = phone_b.call("DELETE", f"/encore/api/v1/me/devices/{phone_a.device}")
    print("the other phone revokes the lost one:", status)
    lost_token = phone_a.call("GET", "/encore/api/v1/playlists")[0]
    print("a call with the revoked device's token:", lost_token)
    print("wanted: 401 ->", "PASS" if lost_token == 401 else "FAIL")
    salt = secrets.token_hex(4)
    login = f"?u={name}&t={hashlib.md5((password + salt).encode()).hexdigest()}&s={salt}&v=1.16.1&c=audit&f=json"
    app_style = Phone(stack)
    request = urllib.request.Request(app_style.base + "/encore/api/v1/playlists" + login, headers={"X-Encore-Device": phone_a.device})
    try:
        with urllib.request.urlopen(request, timeout=60) as response:
            status = response.status
    except urllib.error.HTTPError as error:
        status = error.code
    print("a call in the app's own style (music-server login in the address, the revoked device named in a header):", status)
    print("wanted: 401 ->", "PASS" if status == 401 else "FAIL (the revoked phone still reads and writes)")


def check_authz(stack: Path) -> None:
    """A member (made through an invitation, so the join path is exercised too) against the owner's data and the owner-only routes."""
    env = env_of(stack)
    owner = Phone(stack)
    status, body = owner.call("POST", "/encore/api/v1/auth/login", {"username": OWNER, "password": env["TEST_OWNER_PASSWORD"], "deviceName": "authz-owner"})
    assert status == 200, (status, body)
    owner.token, owner_id = body["deviceToken"], body["person"]["id"]
    status, body = owner.call("POST", "/encore/api/v1/invites", {"note": "authz check"})
    assert status in (200, 201), (status, body)
    code = body["invite"]["code"]
    member, name, password = Phone(stack), "member" + secrets.token_hex(3), secrets.token_urlsafe(18)
    status, body = member.call("POST", "/encore/api/v1/auth/join", {"code": code, "username": name, "password": password, "displayName": "Authz Member", "deviceName": "authz-member"})
    assert status in (200, 201), ("join", status, body)
    member.token, member_id = body["deviceToken"], body["person"]["id"]
    print("a member joined by invitation; roles:", body["person"]["role"])
    made = owner.call("POST", "/encore/api/v1/playlists", {"name": "Owner private"})[1]["id"]
    fails: list[str] = []

    def expect(label: str, got: int, wanted: tuple[int, ...]) -> None:
        print(("PASS " if got in wanted else "FAIL ") + f"{label}: {got} (wanted {'/'.join(map(str, wanted))})")
        if got not in wanted:
            fails.append(label)

    api = "/encore/api/v1"
    expect("member reads the owner's playlist", member.call("GET", f"{api}/playlists/{made}")[0], (403, 404))
    expect("member renames the owner's playlist", member.call("PATCH", f"{api}/playlists/{made}", {"name": "pwned"})[0], (403, 404))
    expect("member adds songs to the owner's playlist", member.call("POST", f"{api}/playlists/{made}/entries", {"songs": []})[0], (403, 404))
    gone = member.call("DELETE", f"{api}/playlists/{made}")
    expect("member's delete of the owner's playlist changes nothing", 0 if gone[0] == 200 and gone[1].get("changed") is False else gone[0], (0, 403, 404))
    still = owner.call("GET", f"{api}/playlists/{made}")[1]
    expect("the owner's playlist is still there and not renamed", 200 if still.get("name") == "Owner private" and not still.get("deleted") else 500, (200,))
    for label, method, path, body in (
        ("member lists the people", "GET", "/people", None),
        ("member lists the invitations", "GET", "/invites", None),
        ("member makes an invitation", "POST", "/invites", {"note": "x"}),
        ("member demotes the owner", "PATCH", f"/people/{owner_id}", {"role": "member"}),
        ("member promotes themself", "PATCH", f"/people/{member_id}", {"role": "owner"}),
        ("member locks the owner", "PATCH", f"/people/{owner_id}", {"locked": True}),
        ("member resets the owner's password", "POST", f"/people/{owner_id}/reset", {}),
        ("member removes the owner", "DELETE", f"/people/{owner_id}", None),
    ):
        expect(label, member.call(method, api + path, body)[0], (403,))
    member.call("PATCH", f"{api}/me", {"role": "owner"})
    again = member.call("POST", f"{api}/auth/login", {"username": name, "password": password, "deviceName": "authz-member-2"})[1]
    expect("a member who asks for the owner role through /me stays a member", 200 if again["person"]["role"] == "member" else 500, (200,))
    expect("no token on a private route", Phone(stack).call("GET", f"{api}/playlists")[0], (401,))
    owner.call("DELETE", f"{api}/playlists/{made}")
    print("result:", "all PASS" if not fails else f"FAIL: {fails}")


def check_homedoor(stack: Path) -> None:
    """B-56: a visitor whose address Docker hides is seen as the Docker gateway (private, so 'home'). Nothing is forwarded here, which is exactly what
    a router's port forward to Docker Desktop, rootless Docker or Podman delivers."""
    base = f"http://127.0.0.1:{PORT}"
    for path, method in (("/app/", "GET"), ("/auth/login", "POST"), ("/api/user", "GET")):
        request = urllib.request.Request(base + path, method=method, data=b"{}" if method == "POST" else None)
        try:
            with urllib.request.urlopen(request, timeout=30) as response:
                status = response.status
        except urllib.error.HTTPError as error:
            status = error.code
        print(f"the music server's {path} through the gateway, address not forwarded:", status)
        print("wanted: 404 ->", "PASS" if status == 404 else "FAIL (answered as if from the home network)")
    salt = secrets.token_hex(4)
    token = hashlib.md5(("nope" + salt).encode()).hexdigest()
    try:
        urllib.request.urlopen(f"{base}/encore/api/v1/playlists?u=homedoor{salt}&t={token}&s={salt}&v=1.16.1&c=audit&f=json", timeout=30)
    except urllib.error.HTTPError:
        pass
    seen = [line for line in compose(stack, "logs", "--tail", "40", "encore-server").stdout.splitlines() if "counted against address" in line and f"homedoor{salt}" in line]
    print("the address the server counted that caller against:", seen[-1].rsplit(" ", 1)[-1] if seen else "(not found in the log)")


def check_prune(stack: Path) -> None:
    music = Path(env_of(stack)["ENCORE_MUSIC_DIR"])
    away = stack / "music_away"
    away.mkdir(exist_ok=True)
    before = db_count(stack, "select count(*) from song_file")
    for child in list(music.iterdir()):
        shutil.move(str(child), str(away / child.name))
    try:
        scan = (
            "from encore_server.config import Settings;from encore_server.navidrome import NavidromeClient;import time;"
            "s=Settings.from_env();c=NavidromeClient(s.navidrome_url,s.navidrome_admin_user,s.navidrome_admin_password);"
            "c.start_scan(full=True);time.sleep(8);print('the music server now lists', len(c.songs(0,500) or []), 'songs')"
        )
        print(compose(stack, "exec", "-T", "encore-server", "python", "-c", scan).stdout.strip())
        seen = compose(stack, "logs", "encore-server").stdout.count("library linked")
        compose(stack, "restart", "encore-server")
        for _ in range(40):
            if compose(stack, "logs", "encore-server").stdout.count("library linked") > seen:
                break
            time.sleep(3)
        after = db_count(stack, "select count(*) from song_file")
    finally:
        for child in list(away.iterdir()):
            shutil.move(str(child), str(music / child.name))
    print("file links before:", before, "| after the empty answer:", after, "(the music is back in its folder now)")
    print("wanted: unchanged ->", "PASS" if before == after else "FAIL")


def check_transient(stack: Path) -> None:
    override = stack / "docker-compose.override.yml"
    override.write_text("services:\n  encore-server:\n    extra_hosts:\n" + "".join(f'      - "{h}:127.0.0.1"\n' for h in YOUTUBE_HOSTS), encoding="utf-8")
    set_env(stack, "ENCORE_YOUTUBE", "1")
    compose(stack, "up", "-d")
    for _ in range(40):
        if "healthy" in compose(stack, "ps", "encore-server", "--format", "{{.Status}}").stdout:
            break
        time.sleep(3)
    phone = Phone(stack)
    phone.sign_in()
    status, body = phone.call("POST", "/encore/api/v1/refs/resolve", {"songs": [{"title": "Maria Tambien", "artists": ["Khruangbin"], "durationMs": 215000}]})
    ref = body["items"][0]["id"]
    phone.call("PUT", f"/encore/api/v1/likes/{ref}", {})
    state: dict = {}
    for _ in range(40):
        status, state = phone.call("GET", f"/encore/api/v1/refs/{ref}/keep")
        if state.get("state") in ("failed", "kept", "none"):
            break
        time.sleep(3)
    status, answer = phone.call("POST", "/encore/api/v1/keep/progress", {"groups": [{"kind": "liked", "id": "liked"}]})
    group = answer["groups"][0]
    status, retry = phone.call("POST", "/encore/api/v1/keep/retry", {"kind": "liked", "id": "liked"})
    set_env(stack, "ENCORE_YOUTUBE", "0")
    override.unlink()
    compose(stack, "up", "-d")
    print("YouTube unreachable (its names point to the container itself; no traffic leaves the PC). The liked song is:", state)
    print("the download screen is told: failed", group["failed"], "retryable", group["retryable"], "| Retry asked for", retry.get("retried"), "songs")
    print("wanted: still waiting, or failed with Retry offered ->", "PASS" if group["retryable"] else "FAIL")


def connections(stack: Path) -> None:
    code = (
        "n=0\nfor f in ('/proc/net/tcp','/proc/net/tcp6'):\n    for line in open(f).read().splitlines()[1:]:\n"
        "        p=line.split()\n        if p[1].endswith(':11B5') and p[3]=='01': n+=1\nprint(n)\n"
    )
    print("established connections to the server's port 4533:", compose(stack, "exec", "-T", "encore-server", "python", "-c", code).stdout.strip())


