def check_library(stack: Path) -> None:
    phone = Phone(stack)
    phone.sign_in()
    refs: dict[str, dict] = {}
    for _ in range(40):  # the library link runs 20 s after the start, after the music server has scanned
        refs = phone.refs()
        if refs:
            break
        time.sleep(5)
    print(f"{len(TRACKS)} files in the music folder; the server made {len(refs)} songs")
    for r in sorted(refs.values(), key=lambda x: x["title"]):
        print("  ", r["title"], "|", r["artists"], "|", r["durationMs"], "ms")
    print("song_file rows, distinct songs:", db_count(stack, "select count(*), count(distinct ref) from song_file"))
    print(f"wanted: {len(TRACKS)} songs ->", "PASS" if len(refs) == len(TRACKS) else "FAIL")


def check_outage(stack: Path) -> None:
    compose(stack, "stop", "navidrome")
    try:
        status, body = Phone(stack).call("POST", "/encore/api/v1/auth/login", {"username": OWNER, "password": env_of(stack)["TEST_OWNER_PASSWORD"], "deviceName": "audit"})
    finally:
        compose(stack, "start", "navidrome")
    print("sign-in with the CORRECT password while the music server is down:", status, json.dumps(body, ensure_ascii=False)[:160])
    print("wanted: 503 'not answering', not counted as a wrong guess ->", "PASS" if status == 503 else "FAIL")


