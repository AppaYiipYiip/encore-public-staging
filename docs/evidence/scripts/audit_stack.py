def up(stack: Path, rebuild: bool) -> None:
    if rebuild or run("docker", "image", "inspect", IMAGE).returncode != 0:
        print("building the image from this checkout (a few minutes the first time) ...")
        run("docker", "build", "-t", IMAGE, str(REPO / "server" / "encore_server"), check=True)
    stack.mkdir(parents=True, exist_ok=True)
    music = stack / "music"
    music.mkdir(exist_ok=True)
    shutil.copy(REPO / "server" / "encore_server" / "deploy" / "compose.yaml", stack / "compose.yaml")
    if not (stack / ".env").exists():
        values = {
            "ENCORE_MUSIC_DIR": str(music).replace("\\", "/"),
            "ENCORE_PORT": PORT,
            "ENCORE_IMAGE": IMAGE.split(":")[0],
            "ENCORE_TAG": IMAGE.split(":")[1],
            "ENCORE_SERVER_NAME": "Audit test server",
            "ENCORE_NAVIDROME_ADMIN_USER": "encore-admin",
            "ENCORE_NAVIDROME_ADMIN_PASSWORD": secrets.token_urlsafe(18),
            "ENCORE_YOUTUBE": "0",
            "ENCORE_AUTO_TOOLS": "0",
            "TEST_OWNER_PASSWORD": secrets.token_urlsafe(14),
        }
        (stack / ".env").write_text("\n".join(f"{k}={v}" for k, v in values.items()) + "\n", encoding="utf-8")
    for folder, stem, title, artist, album, track, seconds in TRACKS:
        (music / folder).mkdir(exist_ok=True)
        if (music / folder / f"{stem}.flac").exists():
            continue
        done = run(
            "docker", "run", "--rm", "-v", f"{music}:/music", "--entrypoint", "ffmpeg", IMAGE, "-y", "-loglevel", "error",
            "-f", "lavfi", "-i", f"sine=frequency={220 + track * 55}:duration={seconds}",
            "-metadata", f"title={title}", "-metadata", f"artist={artist}", "-metadata", f"album={album}",
            "-metadata", f"track={track}", "-metadata", f"album_artist={artist}", "-c:a", "flac", f"/music/{folder}/{stem}.flac",
        )
        print("track", "ok" if done.returncode == 0 else "FAILED", folder, stem, done.stderr.strip()[:100])
    compose(stack, "up", "-d")
    for _ in range(40):
        if "healthy" in compose(stack, "ps", "encore-server", "--format", "{{.Status}}").stdout:
            break
        time.sleep(3)
    payload = json.dumps({"username": OWNER, "password": env_of(stack)["TEST_OWNER_PASSWORD"], "name": "Audit Owner"})
    done = compose(stack, "exec", "-T", "encore-server", "python", "-m", "encore_server", "setup", stdin=payload)
    print("first-install step:", done.stdout.strip().replace("\n", ", ") or done.stderr.strip()[:200])
    print(f"ready: http://127.0.0.1:{PORT}  (an emulator reaches it at 10.0.2.2:{PORT}; user {OWNER}, the password is in {stack / '.env'}, key TEST_OWNER_PASSWORD)")


# ------------------------------------------------------------------------------------------------------------ http


class Phone:
    """What a phone does: sign in once, then call with the device token."""

    def __init__(self, stack: Path) -> None:
        self.base = f"http://127.0.0.1:{PORT}"
        self.env = env_of(stack)
        self.token: str | None = None

    def call(self, method: str, path: str, body: object | None = None, raw: bool = False):
        request = urllib.request.Request(self.base + path, data=json.dumps(body).encode() if body is not None else None, method=method)
        request.add_header("Content-Type", "application/json")
        if self.token:
            request.add_header("Authorization", f"Bearer {self.token}")
        try:
            with urllib.request.urlopen(request, timeout=60) as response:
                text = response.read().decode("utf-8", "replace")
                return response.status, (text if raw else json.loads(text or "{}"))
        except urllib.error.HTTPError as error:
            text = error.read().decode("utf-8", "replace")
            try:
                return error.code, (text if raw else json.loads(text or "{}"))
            except ValueError:
                return error.code, text

    def sign_in(self) -> None:
        status, body = self.call("POST", "/encore/api/v1/auth/login", {"username": OWNER, "password": self.env["TEST_OWNER_PASSWORD"], "deviceName": "audit"})
        if status != 200:
            raise SystemExit(f"sign-in failed: {status} {body}")
        self.token = body["deviceToken"]

    def refs(self) -> dict[str, dict]:
        found: dict[str, dict] = {}
        since = "0"
        while True:
            status, body = self.call("GET", f"/encore/api/v1/library/files?since={since}&limit=500")
            assert status == 200, (status, body)
            found.update({r["id"]: r for r in body["refs"]})
            since = body["cursor"]
            if not body.get("more"):
                return found


def db_count(stack: Path, sql: str) -> str:
    code = f"import sqlite3;print(sqlite3.connect('/data/encore.db').execute({sql!r}).fetchone())"
    return compose(stack, "exec", "-T", "encore-server", "python", "-c", code).stdout.strip()


