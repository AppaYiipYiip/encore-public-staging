"""Writes the admin website's colours, spacing, radii and motion from the app's own design file, so the two cannot drift apart.

    python tool/gen_admin_tokens.py            # rewrites server/encore-admin/encore_admin/static/tokens.css
    python tool/gen_admin_tokens.py --check    # exits 1 when the file is not what the design file says (the tests run this)
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "app" / "lib" / "design" / "tokens.dart"
TARGET = ROOT / "server" / "legacy" / "encore-admin" / "encore_admin" / "static" / "tokens.css"

FIELDS = ["bg", "surface", "surfaceHigh", "outline", "onBg", "onBgMuted", "onBgFaint", "accent", "onAccent", "danger", "warning"]


def _kebab(name: str) -> str:
    return re.sub(r"([A-Z])", lambda m: "-" + m.group(1).lower(), name)


def _rgba(hex6: str, alpha: float | None) -> str:
    value = hex6.upper()
    if alpha is None:
        return "#" + value
    r, g, b = int(value[0:2], 16), int(value[2:4], 16), int(value[4:6], 16)
    return f"rgba({r}, {g}, {b}, {alpha:g})"


def _factory(text: str, name: str) -> dict[str, str]:
    start = text.index(f"factory EncoreColors.{name}(")
    body = text[text.index("return EncoreColors(", start): text.index(");", text.index("return EncoreColors(", start))]
    accent = re.search(r"Color accent = (?:kDefaultAccent|const Color\(0xFF([0-9A-Fa-f]{6})\))", text[start:start + 200])
    default_accent = re.search(r"const Color kDefaultAccent = Color\(0xFF([0-9A-Fa-f]{6})\)", text).group(1)
    accent_hex = accent.group(1) if accent and accent.group(1) else default_accent
    out: dict[str, str] = {}
    for field in FIELDS:
        if field == "accent":
            out[field] = "#" + accent_hex.upper()
            continue
        m = re.search(rf"{field}:\s*(?:amoled \? const Color\(0xFF[0-9A-Fa-f]{{6}}\) : )?const Color\(0xFF([0-9A-Fa-f]{{6}})\)"
                      rf"(?:\.withValues\(alpha: ([0-9.]+)\))?", body)
        out[field] = _rgba(m.group(1), float(m.group(2)) if m.group(2) else None)
    return out


def render() -> str:
    text = SOURCE.read_text(encoding="utf-8")
    dark, light = _factory(text, "dark"), _factory(text, "light")
    space = dict(re.findall(r"static const double (\w+) = (\d+);", text[text.index("abstract final class Space"):text.index("abstract final class Radii")]))
    radii = dict(re.findall(r"static const double (\w+) = (\d+);", text[text.index("abstract final class Radii"):text.index("abstract final class Motion")]))
    motion = dict(re.findall(r"static const Duration (\w+) = Duration\(milliseconds: (\d+)\);", text))

    def block(values: dict[str, str]) -> str:
        return "\n".join(f"  --{_kebab(k)}: {v};" for k, v in values.items())

    shared = [f"  --space-{_kebab(k)}: {v}px;" for k, v in space.items()]
    shared += [f"  --radius-{_kebab(k)}: {v}px;" for k, v in radii.items()]
    shared += [f"  --motion-{_kebab(k)}: {v}ms;" for k, v in motion.items()]
    return (
        "/* Generated by tools/gen_admin_tokens.py from app/lib/design/tokens.dart. Do not edit by hand. */\n"
        "@font-face { font-family: 'Figtree'; font-weight: 400; font-style: normal; font-display: swap; src: url('/fonts/Figtree-Regular.ttf') format('truetype'); }\n"
        "@font-face { font-family: 'Figtree'; font-weight: 500; font-style: normal; font-display: swap; src: url('/fonts/Figtree-Medium.ttf') format('truetype'); }\n"
        "@font-face { font-family: 'Figtree'; font-weight: 600; font-style: normal; font-display: swap; src: url('/fonts/Figtree-SemiBold.ttf') format('truetype'); }\n"
        "@font-face { font-family: 'Figtree'; font-weight: 700; font-style: normal; font-display: swap; src: url('/fonts/Figtree-Bold.ttf') format('truetype'); }\n"
        ":root {\n" + "\n".join(shared) + "\n  --gutter: " + space["gutter"] + "px;\n"
        "  color-scheme: dark;\n" + block(dark) + "\n}\n"
        "@media (prefers-color-scheme: light) {\n  :root:not([data-theme=\"dark\"]) {\n    color-scheme: light;\n"
        + "\n".join("  " + line for line in block(light).splitlines()) + "\n  }\n}\n"
        ":root[data-theme=\"light\"] {\n  color-scheme: light;\n" + block(light) + "\n}\n"
    )


def main() -> int:
    wanted = render()
    if "--check" in sys.argv:
        have = TARGET.read_text(encoding="utf-8") if TARGET.exists() else ""
        if have.replace("\r\n", "\n") != wanted:
            print("tokens.css is out of date: run python tool/gen_admin_tokens.py", file=sys.stderr)
            return 1
        return 0
    TARGET.write_text(wanted, encoding="utf-8", newline="\n")
    print(f"wrote {TARGET.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
