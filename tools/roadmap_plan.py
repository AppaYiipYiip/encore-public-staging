#!/usr/bin/env python3
"""The plan as data: ONE implementation of the rules, shared by tools/check_order.py (CI) and tools/roadmap_board.py (the owner's local board).

Where each fact lives (one place each, so nothing can disagree):
  * docs/tasks/P*.md      what a task is, its size (S, M, L), and its NEEDS:  `* **Order.** Needs: P2-08 [d], P2-09 [i]. Why: ...`
  * docs/roadmap/order.json   the SEQUENCE of what is not walked yet: `order` = NOW, one flat list (no phases, D-57), and `later` = future work to keep in mind and not
                              bother with (D-58). The owner edits this by dragging; a move CARRIES what the item needs or what needs it (see move_item).
  * docs/roadmap/status.json  the state of an item: todo, built (built, not walked) or walked (with its evidence). Only agents change it, with `roadmap.py mark`, in the PR of the work.
  * docs/roadmap/notes/       the owner's own checks (type `check`: "I did this", "I checked it") and reports (type `problem`: "it does not work"). The state the board shows is
                              DERIVED from status.json and these notes, so status.json keeps one writer: a problem reopens an item until an agent marks it again; an item only
                              the owner can finish (kind `owner`) is done when he says so; for an item whose acceptance is his judgement (`judge`) his check is recorded and
                              cited when an agent marks it walked.
  * docs/roadmap/items.json   plain-words titles, kinds, notes, and the not-yet-accepted PROPOSALS (N-ids, with their own size and needs).
  * docs/08-roadmap.md        the explanation; the list inside it is GENERATED from order.json.

A need is `[d]` declared in the task's own text, `[i]` inferred (technical: it cannot be built without it), or `[p]` POLICY (a rule the project chose,
e.g. "tablet only after the public release"). A policy need only warns when the order breaks it; the owner may override it knowingly. A hard need
([d] or [i]) is an error: the item that needs something must come AFTER it in the list (or the needed item must be walked).
"""
from __future__ import annotations

import hashlib
import json
import os
import re
import tempfile
from dataclasses import dataclass, field
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TASK_GLOB = "docs/tasks/P[0-9]*.md"
ROADMAP = "docs/08-roadmap.md"
PLAN = "docs/roadmap"
BEGIN = "<!-- order:begin (generated by tools/check_order.py --write; do not edit by hand) -->"
END = "<!-- order:end -->"

#: SIZE_DAYS: what S, M and L mean in Claude Code working days for ONE agent (an assumption: only a way to compare). RATE: the MEASURED speed of the whole
#: team, Claude-days of finished tasks per weekday: the 15 tasks finished by new work in this repository (51 Claude-days; P1-08, P1-09 and P1-11 are
#: left out because their code arrived with the 21 Oct import) over the 10 weekdays 21 Oct to 3 Nov. Sensitivity: counted from 14 Oct, when the earlier project
#: started, the speed would be about 3.9. Recompute at each gate. SLOWDOWN: a stated judgement for what is left (it needs the owner, real devices, outside gates,
#: and the usage limit has stopped the work twice). BUILT_REMAINING: a built-but-not-walked item still costs this share of its size (the walk and the fixes).
SIZE_DAYS = {"S": 1, "M": 3, "L": 7}
RATE = 5.1
SLOWDOWN = (1.5, 3.0)
BUILT_REMAINING = 0.25
STATES = ("todo", "built", "walked")
BEHIND = "Behind the scenes:"
#: words the owner (not a coder) does not know: they belong in the details, never in a title (whole words, case-sensitive: "smart shuffle" is fine)
BANNED_IN_TITLES = ("CI", "b11", "ratchet", "Navidrome", "OpenAPI", "ultrareview", "Docker", "Funnel", "Tailscale", "yt-dlp")

TASK_ID = r"P\d-\d+[a-z]?"
ANY_ID = rf"(?:{TASK_ID}|N-\d+)"
HEADING = re.compile(rf"^## ({TASK_ID})\b[\s:—-]*(.*)$", re.M)
ORDER_LINE = re.compile(r"^\* \*\*Order\.\*\* Needs: (.+?)\.(?: Why: (.+))?\s*$", re.M)
NEED = re.compile(rf"^({ANY_ID})(?: \[([dip])\])?$")


@dataclass
class Task:
    tid: str
    title: str
    size: str
    file: str
    needs: list[tuple[str, str]]
    why: str | None
    has_line: bool


@dataclass
class Plan:
    tasks: dict[str, Task] = field(default_factory=dict)
    items: dict[str, dict] = field(default_factory=dict)
    status: dict[str, dict] = field(default_factory=dict)
    order: list = field(default_factory=list)
    later: list = field(default_factory=list)
    version: str = ""
    proposed_md: set = field(default_factory=set)
    errors: list[str] = field(default_factory=list)
    reopened: set = field(default_factory=set)          # the owner reported a problem after the item was last marked: it needs work again
    owner_done: set = field(default_factory=set)        # an item only the owner can finish, and he said he did
    owner_checks: dict = field(default_factory=dict)    # item -> his latest check note (kept for display and for the walk evidence)
    problems: dict = field(default_factory=dict)        # item -> his latest problem note that still counts


# ------------------------------------------------------------------------------------------------------------------ reading
def parse_tasks(texts: dict[str, str]) -> tuple[dict[str, Task], list[str]]:
    tasks: dict[str, Task] = {}
    errors: list[str] = []
    for fname, text in texts.items():
        marks = list(HEADING.finditer(text))
        for i, m in enumerate(marks):
            tid = m.group(1)
            body = text[m.end(): marks[i + 1].start() if i + 1 < len(marks) else len(text)]
            head = m.group(2)
            size_m = re.search(r"Size\s+([SML])\b", head)
            extra = re.search(r"\+\s*(\d+)\s*days", head)
            size = (size_m.group(1) if size_m else "") + ("+" + extra.group(1) if extra else "")
            title = re.sub(r"\s*[—-]*\s*Size.*$", "", head).strip(" :—-")
            if tid in tasks:
                errors.append(f"{tid}: defined twice ({tasks[tid].file} and {fname})")
                continue
            o = ORDER_LINE.search(body)
            if not o:
                tasks[tid] = Task(tid, title, size, fname, [], None, False)
                continue
            needs: list[tuple[str, str]] = []
            raw = o.group(1).strip()
            if raw.lower() != "none":
                for part in [p.strip() for p in raw.split(",")]:
                    nm = NEED.match(part)
                    if not nm or not nm.group(2):
                        errors.append(f"{tid}: cannot read the need {part!r} (write `P2-08 [d]`, `P2-09 [i]`, `P6-04 [p]` or `none`)")
                        continue
                    needs.append((nm.group(1), nm.group(2)))
            tasks[tid] = Task(tid, title, size, fname, needs, o.group(2), True)
    return tasks, errors


def _json(path: Path, default):
    return json.loads(path.read_text(encoding="utf-8")) if path.exists() else default


def load(root: Path = ROOT) -> Plan:
    p = Plan()
    texts = {f.name: f.read_text(encoding="utf-8") for f in sorted(root.glob(TASK_GLOB))}
    p.tasks, p.errors = parse_tasks(texts)
    pm = root / "docs/tasks/PROPOSED.md"
    p.proposed_md = set(re.findall(r"^\| (N-\d+) \|", pm.read_text(encoding="utf-8"), flags=re.M)) if pm.exists() else set()
    p.items = _json(root / PLAN / "items.json", {})
    p.status = _json(root / PLAN / "status.json", {})
    op = root / PLAN / "order.json"
    if op.exists():
        raw = json.loads(op.read_text(encoding="utf-8"))
        p.order = raw.get("order", [])
        p.later = raw.get("later", [])
        extra = sorted(set(raw) - {"order", "later"})
        if extra:      # an old or foreign writer (a server still running old code left a save counter in it on 3 Nov 2026)
            p.errors.append(f"order.json: unknown key(s) {extra}; the file holds only \"order\" and \"later\" (delete the line: it came from a writer running old code)")
    p.version = hashlib.sha256(op.read_bytes()).hexdigest()[:16] if op.exists() else ""  # the token a page must hand back to save
    _derive_owner_marks(p, root)
    return p


def _derive_owner_marks(p: Plan, root: Path) -> None:
    """From the owner's `check` and `problem` notes (not retracted) and the time of the item's last mark in status.json (`at`; an old entry has none, so any report counts)."""
    import roadmap_notes as rn      # here, not at the top: the notes module needs nothing from this one
    notes, _ = rn.read_all(root)
    for item in sorted({n["item"] for n in notes if n.get("type") in ("check", "problem")}):
        view = [n for n in rn.thread(notes, item) if n["role"] == "owner"]
        checks = [n for n in view if n.get("type") == "check"]
        problems = [n for n in view if n.get("type") == "problem"]
        marked_at = p.status.get(item, {}).get("at", "")
        base = p.status.get(item, {}).get("state", "todo")
        last_check = checks[-1] if checks else None
        live_problems = [n for n in problems if n["at"] > marked_at and (last_check is None or n["at"] > last_check["at"])]
        if live_problems:
            p.problems[item] = live_problems[-1]
            if base in ("built", "walked"):
                p.reopened.add(item)
        if last_check is not None and not live_problems:
            p.owner_checks[item] = last_check
            if p.items.get(item, {}).get("kind") == "owner":
                p.owner_done.add(item)


# ------------------------------------------------------------------------------------------------------------------ the facts about an item
def size_of(p: Plan, tid: str) -> str:
    if tid in p.tasks:
        return p.tasks[tid].size or "M"
    return p.items.get(tid, {}).get("size", "M")


def needs_of(p: Plan, tid: str) -> list[tuple[str, str]]:
    if tid in p.tasks:
        return p.tasks[tid].needs
    return [(n["id"], n.get("mark", "i")) for n in p.items.get(tid, {}).get("needs", [])]


def title_of(p: Plan, tid: str) -> str:
    return p.items.get(tid, {}).get("title") or (p.tasks[tid].title if tid in p.tasks else tid)


def why_of(p: Plan, tid: str) -> str | None:
    return p.tasks[tid].why if tid in p.tasks else p.items.get(tid, {}).get("why")


def state_of(p: Plan, tid: str) -> str:
    """What the board shows: todo, built, reopened (the owner reported a problem), or walked (proven; or, for an item only he can finish, his word)."""
    if tid in p.owner_done:
        return "walked"
    if tid in p.reopened:
        return "reopened"
    return p.status.get(tid, {}).get("state", "todo")


def evidence_of(p: Plan, tid: str) -> str:
    if tid in p.owner_done and p.status.get(tid, {}).get("state") != "walked":
        c = p.owner_checks[tid]
        return f"you said you did this on {c['at'][:10]}: {c['body']}"
    return p.status.get(tid, {}).get("evidence", "")


def agent_days(size: str) -> float:
    base = size.split("+")[0] or "M"
    return SIZE_DAYS[base] + (int(size.split("+")[1]) if "+" in size else 0)


def remaining_days(p: Plan, tid: str) -> float:
    st = state_of(p, tid)
    if st == "walked" or p.items.get(tid, {}).get("kind") == "owner":
        return 0.0                                      # the owner's own steps are not in the numbers (docs/08), so a pink item costs no Claude-days
    full = agent_days(size_of(p, tid))
    return full * (BUILT_REMAINING if st in ("built", "reopened") else 1.0)       # a fix and a new walk cost about as much as a walk


def flat_ids(order: list) -> list[str]:
    """The ids of the plan, in order. (Anything that is not an id is reported by validate().)"""
    return [e for e in order if isinstance(e, str)]


# ------------------------------------------------------------------------------------------------------------------ the rules
def validate(p: Plan) -> tuple[list[str], list[str]]:
    """Returns (errors, warnings). Errors fail CI and refuse a save on the board; warnings are shown (a policy the owner chose to override)."""
    err: list[str] = list(p.errors)
    warn: list[str] = []
    ids = flat_ids(p.order)
    lids = flat_ids(p.later)
    pos = {t: i for i, t in enumerate(ids)}
    lpos = {t: i for i, t in enumerate(lids)}
    walked = {t for t in set(p.status) | p.owner_done if state_of(p, t) == "walked"}      # derived: a reopened item is not walked any more
    known = set(p.tasks) | {t for t, v in p.items.items() if v.get("proposal")}

    for t, s in p.status.items():
        if s.get("state") not in STATES:
            err.append(f"status.json: {t} has state {s.get('state')!r} (use one of {', '.join(STATES)})")
        if s.get("state") == "walked" and not s.get("evidence"):
            err.append(f"status.json: {t} is walked but names no evidence (a record in docs/evidence, a pull request, a measurement)")
        if t not in known:
            err.append(f"status.json: {t} is not a task")
    # every id once: in the order, or walked, never both, never twice
    seen: dict[str, int] = {}
    for t in ids + lids:
        seen[t] = seen.get(t, 0) + 1
    for t, n in seen.items():
        if n > 1:
            err.append(f"order.json: {t} appears {n} times (in Now and Later together)")
        if t not in known:
            err.append(f"order.json: {t} is not a task or a proposal")
        if t in walked:
            err.append(f"order.json: {t} is walked, so it must leave the lists (status.json says walked)")
    for t, task in p.tasks.items():
        if t not in seen and t not in walked:
            err.append(f"{t}: in no place of the plan (add it to order.json, or mark it walked in status.json with its evidence)")
        if not task.has_line:
            err.append(f"{t} ({task.file}): no `* **Order.** Needs: ...` line")
        if t not in p.items:
            err.append(f"{t}: no plain-words title in docs/roadmap/items.json")
    for t, v in p.items.items():
        if not v.get("title") or not v.get("kind"):
            err.append(f"items.json: {t} needs a title and a kind")
            continue
        # titles are plain words (D-59): the owner is not a coder. A "Behind the scenes:" title is invisible work (kind plumbing or process) and nothing else is;
        # no item id and none of the banned jargon words in a title; long titles only warn.
        title, kind = v["title"], v["kind"]
        behind = title.startswith(BEHIND)
        if behind and kind not in ("plumbing", "process"):
            err.append(f"items.json: {t}: the title starts with \"{BEHIND}\" but its kind is {kind} (use plumbing or process)")
        if not behind and kind in ("plumbing", "process"):
            err.append(f"items.json: {t}: its kind is {kind} (invisible work), so its title must start with \"{BEHIND}\" (or the kind is wrong)")
        if re.search(rf"\b{ANY_ID}\b", title):
            err.append(f"items.json: {t}: the title names an item id; titles are plain words (D-59)")
        words = [w for w in BANNED_IN_TITLES if re.search(rf"\b{re.escape(w)}\b", title)]
        if words:
            err.append(f"items.json: {t}: the title uses jargon the owner does not know ({', '.join(words)}); move it into the details (D-59)")
        if len(title.split()) > 16:
            warn.append(f"items.json: {t}: the title has {len(title.split())} words; about ten is the aim (D-59)")
    in_json = {t for t, v in p.items.items() if v.get("proposal")}
    # an idea typed on the board is a proposal with `"pending": true` until an agent writes its row in PROPOSED.md (then the flag is removed)
    pending = {t for t in in_json if p.items[t].get("pending")}
    stray = (p.proposed_md - in_json) | ((in_json - pending) - p.proposed_md) | (pending & p.proposed_md)
    if stray:
        err.append(f"tasks/PROPOSED.md and docs/roadmap/items.json list different proposals: {sorted(stray)} "
                   "(an idea added on the board stays `pending` until its row is written; remove `pending` then)")
    # every proposal sits in Now or Later (there is no waiting box: the advisor places each one, the owner's own ideas go where he presses +)
    for t in sorted(in_json):
        if t not in seen and t not in walked:
            err.append(f"{t}: a proposal in no list (put it in Now or Later in order.json)")
    # one flat list: an entry that is not an id (an old milestone divider, say) is refused with a plain message
    for e in list(p.order) + list(p.later):
        if not isinstance(e, str):
            err.append(f"order.json: {json.dumps(e, ensure_ascii=False)} is not an item id: the plan is ONE list with no phases or groups (D-57); remove the entry")
    # needs
    for t in list(p.tasks) + [i for i in p.items if i in seen and i not in p.tasks]:
        for need, mark in needs_of(p, t):
            if t in walked:
                if need not in walked and need in known and need not in p.reopened:       # a reopened need is a bug to fix, not a reason to un-walk what stands on it
                    err.append(f"{t} is walked but needs {need}, which is not")
                continue
            if need == t:
                err.append(f"{t}: needs itself")
                continue
            if need not in known:
                err.append(f"{t}: needs {need}, which is not a task")
                continue
            if mark in ("i", "p") and not why_of(p, t):
                err.append(f"{t}: the need {need} is [{mark}] but has no `Why:` sentence")
            if need in walked:
                continue
            wt = "now" if t in pos else ("later" if t in lpos else None)
            wn = "now" if need in pos else ("later" if need in lpos else None)
            if wt is None or wn is None:
                continue
            if wt == "now" and wn == "later":
                msg = f"{t} is in Now but needs {need}, which is in Later"
                if mark == "p":
                    warn.append(msg + " (a rule of the plan: " + ((why_of(p, t) or "see its Order line").split(";")[0][:110]) + ")")
                else:
                    err.append(msg + f" [{mark}]: move {t} to Later too, or {need} to Now")
                continue
            if wt == "later" and wn == "now":
                continue                                                  # future work may need what is being built now
            P = pos if wt == "now" else lpos
            if P[need] > P[t]:
                msg = f"{t} comes before {need}, which it needs"
                if mark == "p":
                    warn.append(msg + " (a rule of the plan: " + ((why_of(p, t) or "see its Order line").split(";")[0][:110]) + ")")
                else:
                    err.append(msg + f" [{mark}]: it cannot be built without it")
    return err, warn


# ------------------------------------------------------------------------------------------------------------------ estimates
def estimates(p: Plan) -> dict:
    """Per item: cumulative 'ready around working day' (lo, hi); the total of the whole list; and the counts of done, built and still to do.
    finish[i] = the longest chain of needs down to i in agent-days (one agent per task: a chain cannot be split across agents)."""
    ids = flat_ids(p.order)
    finish: dict[str, float] = {}
    cum = 0.0
    per_item: dict[str, dict] = {}
    lo_s, hi_s = SLOWDOWN
    for t in ids:
        rem = remaining_days(p, t)
        base = max([finish.get(n, 0.0) for n, _ in needs_of(p, t) if n in finish] or [0.0])
        finish[t] = base + rem
        cum += rem
        per_item[t] = {"days": agent_days(size_of(p, t)), "remaining": rem,
                       "lo": round(max(finish[t], cum / RATE * lo_s)), "hi": round(max(finish[t] * lo_s, cum / RATE * hi_s))}
    work = sum(remaining_days(p, t) for t in ids)
    total = {"work": work, "lo": round(work / RATE * lo_s), "hi": round(work / RATE * hi_s),
             "weeks_lo": round(work / RATE * lo_s / 5), "weeks_hi": round(work / RATE * hi_s / 5)}
    left = [t for t in ids if state_of(p, t) != "walked"]
    done = sum(1 for t in set(p.status) | p.owner_done if state_of(p, t) == "walked")
    counts = {"done": done, "built": sum(1 for t in left if state_of(p, t) == "built"), "reopened": sum(1 for t in left if state_of(p, t) == "reopened"), "left": len(left), "all": done + len(left),
              "later": len([x for x in flat_ids(p.later) if state_of(p, x) != "walked"])}
    return {"items": per_item, "total": total, "counts": counts}


# ------------------------------------------------------------------------------------------------------------------ the generated table
def render_table(p: Plan) -> str:
    est = estimates(p)
    out = [BEGIN, ""]
    c, t = est["counts"], est["total"]
    out += [f"**The plan, in order** (one list, top = next): {c['left']} items still to do, {c['built']} of them built and waiting for a walk, {c['done']} done. "
            f"About {t['work']:g} Claude-days of work left, so roughly **{t['lo']} to {t['hi']} working days** (about {t['weeks_lo']} to {t['weeks_hi']} weeks) elapsed in all "
            "(external waits and the owner's own steps are not in it). A range from a stated method, never a date. `*` marks a policy need (a rule the project chose, which the owner may override).",
            "", "| # | Item | What | Size | State | Needs | Ready around working day |", "|---|------|------|------|-------|-------|--------------------------|"]
    for i, tid in enumerate([x for x in flat_ids(p.order) if state_of(p, x) != "walked"], 1):
        needs = ", ".join(n + ("*" if mk == "p" else "") for n, mk in needs_of(p, tid)) or "none"
        e = est["items"][tid]
        out.append(f"| {i} | {tid} | {title_of(p, tid)} | {size_of(p, tid)} | {state_of(p, tid)} | {needs} | {e['lo']} to {e['hi']} |")
    out.append("")
    later = [x for x in flat_ids(p.later) if state_of(p, x) != "walked"]
    if later:
        out += [f"**Later** ({len(later)} items: future work to keep in mind and not bother with now, D-58; no estimate)", "", "| Item | What | Size | Needs |", "|------|------|------|-------|"]
        for x in later:
            needs = ", ".join(n + ("*" if mk == "p" else "") for n, mk in needs_of(p, x)) or "none"
            out.append(f"| {x} | {title_of(p, x)} | {size_of(p, x)} | {needs} |")
        out.append("")
    walked = sorted(x for x in set(p.status) | p.owner_done if state_of(p, x) == "walked")
    if walked:
        out += [f"**Done** ({len(walked)} items with their proof; what is left inside them is in `tasks/AUDIT.md`)", "", "| Item | What | Proof |", "|------|------|-------|"]
        for x in walked:
            out.append(f"| {x} | {title_of(p, x)} | {evidence_of(p, x)} |")
        out.append("")
    out.append(END)
    return "\n".join(out)


def refresh_roadmap(p: Plan, root: Path = ROOT) -> tuple[bool, str]:
    road = (root / ROADMAP).read_text(encoding="utf-8").replace("\r\n", "\n")
    pat = re.compile(re.escape(BEGIN) + r".*?" + re.escape(END), re.S)
    m = pat.search(road)
    if not m:
        return False, "markers missing"
    return True, pat.sub(lambda _: render_table(p), road)


# ------------------------------------------------------------------------------------------------------------------ saving (used by the board)
def write_order(root: Path, order: list, later: list | None = None) -> str:
    """One entry per line, so a change of order is a readable diff. Atomic: write a temp file, then replace. `later` None keeps the Later list as it is. Returns the new
    conflict token (a hash of the file: a counter stored in the file would conflict in every merge that touches it)."""
    if later is None:
        op = root / PLAN / "order.json"
        later = json.loads(op.read_text(encoding="utf-8")).get("later", []) if op.exists() else []

    def block(name: str, ids: list) -> list[str]:
        out = [f'  "{name}": [']
        for i, e in enumerate(ids):
            out.append("    " + json.dumps(e, ensure_ascii=False) + ("," if i < len(ids) - 1 else ""))
        return out + ["  ]"]

    lines = ["{"] + block("order", order)
    lines[-1] += ","
    lines += block("later", later) + ["}"]
    d = root / PLAN
    fd, tmp = tempfile.mkstemp(dir=d, prefix=".order-", suffix=".tmp")
    with os.fdopen(fd, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    os.replace(tmp, d / "order.json")
    return load(root).version


def apply_order(root: Path, payload: dict) -> tuple[int, dict]:
    """The board's save. Returns (http status, body). 409 when the file changed since the page loaded (the token is a hash of the file);
    400 when the MOVE creates a hard-need error. Errors that were already there (a missing title, say) never block a drag: the owner cannot fix them on the board."""
    p = load(root)
    if payload.get("version") != p.version:
        return 409, {"error": "the plan changed since this page was loaded (another session, or a status update); the page reloads"}
    new = payload.get("order")
    new_later = payload.get("later", p.later)
    if not isinstance(new, list) or not all(isinstance(e, str) for e in new) or not isinstance(new_later, list) or not all(isinstance(e, str) for e in new_later):
        return 400, {"error": "the order and the later list are lists of item ids"}
    before, _ = validate(p)
    p.order, p.later = new, new_later
    after, warnings = validate(p)
    created = [e for e in after if e not in before]
    if created:
        return 400, {"error": created[0], "details": created}
    return 200, {"ok": True, "version": write_order(root, new, new_later), "warnings": warnings}


# ------------------------------------------------------------------------------------------------------------------ a move carries what it needs
def _hard(p: Plan, t: str) -> list[str]:
    return [n for n, mk in needs_of(p, t) if mk in ("d", "i")]


def move_item(p: Plan, item: str, to: str, before: str | None = None) -> tuple[list[str], list[str], list[str]]:
    """Move `item` into NOW or LATER, in front of `before` (or at the end), and CARRY what a hard need ([d] or [i]) demands, so a drag is never refused:
      * to Later: every Now item that hard-needs it (transitively) goes along, behind it;
      * to Now: its Later hard needs (transitively) come along, in front of it;
      * inside a list: needs that would stay behind it are brought to just before it (moving up), dependents that would stay in front of it are pushed to just
        after it (moving down).
    The item itself always lands where it was dropped; the others move. Policy needs ([p]) only warn and are never carried.
    Returns (now, later, also_moved) with the ids that moved besides the item."""
    now = [x for x in flat_ids(p.order) if x != item]
    later = [x for x in flat_ids(p.later) if x != item]
    live = set(now) | set(later) | {item}
    moved: list[str] = []

    def closure(start: str, nxt) -> set[str]:
        seen: set[str] = set()
        todo = [start]
        while todo:
            for y in nxt(todo.pop()):
                if y in live and y not in seen and y != start:
                    seen.add(y)
                    todo.append(y)
        return seen

    dependents = lambda x: [t for t in live if x in _hard(p, t)]      # noqa: E731
    if to == "later":
        carry = [x for x in now if x in closure(item, dependents)]
        now = [x for x in now if x not in carry]
        idx = later.index(before) if before in later else len(later)
        later[idx:idx] = [item] + carry
        moved += carry
        target = later
    else:
        carry = [x for x in later if x in closure(item, _hard_of(p))]
        later = [x for x in later if x not in carry]
        idx = now.index(before) if before in now else len(now)
        now[idx:idx] = carry + [item]
        moved += carry
        target = now
    # inside the list the item landed in: the item stays where it was dropped, everything else is repaired around it
    target[:], extra = _stabilise(p, target, item)
    also = []
    for x in moved + extra:
        if x not in also and x != item:
            also.append(x)
    return now, later, also


def _stabilise(p: Plan, lst: list[str], item: str) -> tuple[list[str], list[str]]:
    """Make `lst` respect every hard need without moving `item`: (1) what hard-needs the item and sits in front of it is held and put right behind it, in the same
    order; (2) then the list is walked from the front and every item's unplaced hard needs are put just before it (moving up carries its needs).
    Returns the new list and the ids that moved."""
    inlist = set(lst)
    i = lst.index(item)
    deps: set[str] = set()
    todo = [item]
    while todo:
        y = todo.pop()
        for t in inlist:
            if y in _hard(p, t) and t not in deps and t != item:
                deps.add(t)
                todo.append(t)
    held = [x for x in lst[:i] if x in deps]
    rest = [x for x in lst if x not in held]
    j = rest.index(item)
    lst2 = rest[: j + 1] + held + rest[j + 1:]
    out: list[str] = []
    done: set[str] = set()
    visiting: set[str] = set()
    moved: set[str] = set(held)

    def emit(x: str, natural: bool) -> None:
        if x in done or x in visiting:
            return
        visiting.add(x)
        for n in _hard(p, x):
            if n in inlist and n not in done and n != x:
                emit(n, False)
        visiting.discard(x)
        done.add(x)
        out.append(x)
        if not natural:
            moved.add(x)

    for x in lst2:
        emit(x, True)
    return out, [x for x in out if x in moved and x != item]


def _hard_of(p: Plan):
    return lambda x: _hard(p, x)


def apply_move(root: Path, payload: dict) -> tuple[int, dict]:
    """The board's drag: {version, item, to: now|later, before?}. 409 when the file changed since the page loaded; 400 for an unknown item or a move that would create
    an error that was not there before. Returns also_moved (ids) so the page can say "Also moved: ...", never a refusal for a need."""
    p = load(root)
    if payload.get("version") != p.version:
        return 409, {"error": "the plan changed since this page was loaded (another session, or a status update); the page reloads"}
    item, to, before = payload.get("item"), payload.get("to"), payload.get("before")
    if not isinstance(item, str) or to not in ("now", "later") or not (before is None or isinstance(before, str)):
        return 400, {"error": "a move needs an item and now or later"}
    if item not in set(flat_ids(p.order)) | set(flat_ids(p.later)):
        return 400, {"error": f"{item} is not in the list"}
    now, later, also = move_item(p, item, to, before)
    errs_before, _ = validate(p)
    p.order, p.later = now, later
    errs_after, warnings = validate(p)
    created = [e for e in errs_after if e not in errs_before]
    if created:
        return 400, {"error": created[0], "details": created}
    return 200, {"ok": True, "version": write_order(root, now, later), "also_moved": also, "warnings": warnings}


# ------------------------------------------------------------------------------------------------------------------ an idea typed on the board
IDEA_KINDS = ("feature", "host", "design", "platform")
MAX_TITLE, MAX_NOTE = 120, 600


def _write_items(root: Path, items: dict) -> None:
    d = root / PLAN
    fd, tmp = tempfile.mkstemp(dir=d, prefix=".items-", suffix=".tmp")
    with os.fdopen(fd, "w", encoding="utf-8", newline="\n") as f:
        f.write(json.dumps(items, indent=1, ensure_ascii=False) + "\n")      # the exact format of the file, so adding an idea is a one-item diff
    os.replace(tmp, d / "items.json")


def add_idea(root: Path, title: str, note: str, kind: str, size: str, by: str, position: str = "end") -> dict:
    """The owner types an idea on the board: it becomes the next N-id AND goes straight into the one list, at the top or at the end (his own idea is his yes:
    there is no second list to accept it from). It is marked `pending` until an agent writes its row in tasks/PROPOSED.md. Read-modify-write on items.json,
    retried if an agent changed the file in between (the board never overwrites their edit)."""
    import roadmap_notes as rn      # here, not at the top: the notes module needs nothing from this one, and CI imports this file first
    title, note, by = (title or "").strip(), (note or "").strip(), (by or "").strip()
    if not title or len(title) > MAX_TITLE:
        raise rn.NoteError(f"give the idea a short title (1 to {MAX_TITLE} characters)")
    if len(note) > MAX_NOTE:
        raise rn.NoteError(f"the description is too long ({len(note)} characters; the limit is {MAX_NOTE}). Put the rest in a note on the item")
    if kind not in IDEA_KINDS or size not in SIZE_DAYS:
        raise rn.NoteError(f"the kind is one of {', '.join(IDEA_KINDS)} and the size one of S, M, L")
    if position not in ("top", "end", "later"):
        raise rn.NoteError("the position is top, end or later")
    why = rn.looks_secret(title) or rn.looks_secret(note)
    if why:
        raise rn.NoteError(f"this looks like {why}; nothing secret goes in the plan files")
    path = root / PLAN / "items.json"
    for _ in range(4):
        before = path.read_bytes() if path.exists() else b"{}"
        items = json.loads(before.decode("utf-8"))
        nums = [int(m.group(1)) for k in items for m in [re.match(r"^N-(\d+)$", k)] if m]
        nid = f"N-{max(nums or [0]) + 1:02d}"
        items[nid] = {"kind": kind, "title": title, "note": note, "proposal": True, "pending": True, "size": size, "needs": [], "from": by or "owner"}
        if (path.read_bytes() if path.exists() else b"{}") != before:        # an agent edited the file meanwhile: read it again
            continue
        _write_items(root, items)
        cur = load(root)                                                            # a fresh read: the owner's order may have changed since
        order, later = flat_ids(cur.order), flat_ids(cur.later)
        if position == "later":
            write_order(root, order, later + [nid])
        else:
            write_order(root, [nid] + order if position == "top" else order + [nid], later)
        return {"id": nid, "position": position, **items[nid]}
    raise rn.NoteError("docs/roadmap/items.json keeps changing; try again in a moment")


# ------------------------------------------------------------------------------------------------------------------ marking an item (agents) and checking it (the owner)
def _now_iso() -> str:
    from datetime import datetime, timezone
    return datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")


def _write_status(root: Path, status: dict) -> None:
    d = root / PLAN
    fd, tmp = tempfile.mkstemp(dir=d, prefix=".status-", suffix=".tmp")
    with os.fdopen(fd, "w", encoding="utf-8", newline="\n") as f:
        f.write(json.dumps(status, indent=1, ensure_ascii=False) + "\n")
    os.replace(tmp, d / "status.json")


def mark(root: Path, item: str, state: str, evidence: str = "", by: str = "", now: str | None = None) -> dict:
    """`roadmap.py mark`: the ONE writer of status.json, run by an agent in the PR of the work. Keeps the files consistent in one step: walked takes the item out of
    order.json; built or todo puts it back at the top if it is missing (a reopened item is urgent). `walked` refuses an evidence that names no record, and cites the
    owner's own check when there is one. New entries carry `at` and `by`, so a report of the owner's made after that time reopens the item."""
    import roadmap_notes as rn
    p = load(root)
    if item not in set(p.tasks) | set(p.items):
        raise rn.NoteError(f"{item} is not an item of the plan")
    if state not in STATES:
        raise rn.NoteError(f"the state is one of {', '.join(STATES)}")
    evidence = (evidence or "").strip()
    if state == "walked" and len(evidence) < 12:
        raise rn.NoteError("walked needs its proof: name the record, the pull request or the measurement in a sentence (--evidence \"...\"). Nothing is walked on a say-so")
    if rn.looks_secret(evidence):
        raise rn.NoteError(f"this looks like {rn.looks_secret(evidence)}; nothing secret goes in the plan files")
    chk = p.owner_checks.get(item)
    if state == "walked" and chk:
        evidence += f" | you checked it on {chk['at'][:10]} (note {chk['id']})"
    status = _json(root / PLAN / "status.json", {})
    status[item] = {"state": state, "evidence": evidence, "at": now or _now_iso(), "by": (by or "Claude").strip()[:60]}
    _write_status(root, status)
    order, later = flat_ids(p.order), flat_ids(p.later)
    if state == "walked":
        new, newl = [x for x in order if x != item], [x for x in later if x != item]
    elif item in later:
        new, newl = order, later                                        # future work stays in Later; only its state is recorded
    else:
        new, newl = (order if item in order else _at_the_top(p, order, item)), later
    if (new, newl) != (order, later):
        write_order(root, new, newl)
    return {"item": item, "state": state, "in_order": item in new}


OWNER_ACTIONS = ("finish", "judge", "problem", "uncheck")


def _at_the_top(p: Plan, order: list[str], item: str) -> list[str]:
    """The item moved to the front of the list, but never before something it hard-needs ([d] or [i]) that is still in the list."""
    rest = [x for x in order if x != item]
    pos = max([rest.index(n) + 1 for n, mk in needs_of(p, item) if mk in ("d", "i") and n in rest] or [0])
    return rest[:pos] + [item] + rest[pos:]


def owner_action(root: Path, item: str, action: str, body: str = "", now=None) -> dict:
    """What the owner's buttons do (his own rules: he is not the tester, and "built, not walked" is the word until it is proven on the release-candidate pair):
      finish  an item only he can finish (kind `owner`: protect main, the keystore): "I did this" is the proof; it leaves the list.
      judge   an item whose acceptance is his own judgement (`judge`): his check is recorded; an agent cites it when marking the item walked.
      problem "it does not work": reopens the item at the top of the list and leaves a note waiting for an agent. Allowed on anything built or done.
      uncheck takes his check back (an item he had finished goes back to the top of the list).
    Everything he says is a note (one file, never edited); status.json is untouched, so it keeps one writer."""
    import roadmap_notes as rn
    p = load(root)
    known = set(p.tasks) | set(p.items)
    if item not in known:
        raise rn.NoteError(f"{item} is not an item of the plan")
    if action not in OWNER_ACTIONS:
        raise rn.NoteError(f"the action is one of {', '.join(OWNER_ACTIONS)}")
    meta = p.items.get(item, {})
    st = state_of(p, item)
    order = flat_ids(p.order)
    kw = {"known_items": known, **({"when": now} if now else {})}
    if action == "finish":
        if meta.get("kind") != "owner":
            raise rn.NoteError("only an item that needs you (kind: Needs you) can be finished by your word: for anything else Claude proves it, and you can say it does not work")
        if st == "walked":
            raise rn.NoteError("it is already done")
        n = rn.add(root, item, "owner", "Owner", body.strip() or "I did this.", "check", **kw)
        if item in order or item in p.later:
            write_order(root, [x for x in order if x != item], [x for x in flat_ids(p.later) if x != item])
        return {"note": n["id"], "state": "walked"}
    if action == "judge":
        if not meta.get("judge"):
            raise rn.NoteError("this item is not one whose acceptance is your own judgement")
        n = rn.add(root, item, "owner", "Owner", body.strip() or "I checked it.", "check", **kw)
        return {"note": n["id"], "state": st}
    if action == "problem":
        if st not in ("built", "walked", "reopened"):
            raise rn.NoteError("nothing is built yet, so there is nothing to report. Leave a note instead")
        if not body.strip():
            raise rn.NoteError("say what does not work, in a sentence")
        n = rn.add(root, item, "owner", "Owner", body.strip(), "problem", to=["agent"], **kw)
        write_order(root, _at_the_top(p, order, item), [x for x in flat_ids(p.later) if x != item])      # a regression is urgent: the front of Now (never before what it needs)
        return {"note": n["id"], "state": "reopened"}
    # uncheck
    chk = p.owner_checks.get(item)
    if not chk:
        raise rn.NoteError("you have not checked it, so there is nothing to take back")
    n = rn.add(root, item, "owner", "Owner", "", "check", replaces=chk["id"], **kw)
    if meta.get("kind") == "owner" and item not in order and p.status.get(item, {}).get("state") != "walked":
        write_order(root, _at_the_top(p, order, item))
    return {"note": n["id"], "state": "todo"}
